// Pulls the book list from the Free Use Bible API (github.com/HelloAOLab/bible-api)
// so the reader's book picker and the 365-day guide are built from the same
// canon the API serves. Run when the API's book list changes:
//
//   node scripts/build-bible-data.mjs
import { writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const response = await fetch('https://bible.helloao.org/api/BSB/books.json')
if (!response.ok) throw new Error(`books.json: ${response.status}`)
const { books } = await response.json()

const rows = books
  .sort((a, b) => a.order - b.order)
  .map(book => ({ id: book.id, name: book.commonName || book.name, chapters: book.numberOfChapters, order: book.order, testament: book.order <= 39 ? 'OT' : 'NT' }))

const lines = rows.map(row => `  { id: '${row.id}', name: ${JSON.stringify(row.name)}, chapters: ${row.chapters}, testament: '${row.testament}' },`)
writeFileSync(path.join(root, 'src/lib/bible-books.generated.ts'), `// Generated by scripts/build-bible-data.mjs from https://bible.helloao.org/api/BSB/books.json.
export type BibleBook = { id: string; name: string; chapters: number; testament: 'OT' | 'NT' }

export const BIBLE_BOOKS: BibleBook[] = [
${lines.join('\n')}
]
`)
console.log(`wrote ${rows.length} books, ${rows.reduce((sum, row) => sum + row.chapters, 0)} chapters`)
