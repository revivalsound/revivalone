// Generates placeholder narration for every Rev Academy episode, so the audio
// player works end to end before real recordings exist.
//
//   node --experimental-strip-types scripts/build-academy-audio.mjs
//
// Windows only: it uses the built-in speech voice (System.Speech) and ffmpeg.
// Writes public/audio/academy/<course-slug>/<episode>.mp3 and the durations in
// src/lib/academy-audio.generated.ts. Replace any mp3 with a real recording
// (same file name) and run this script again with --durations-only.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const root = path.resolve(import.meta.dirname, '..')
const { COURSES } = await import(pathToFileURL(path.join(root, 'src/lib/content.ts')).href)
const durationsOnly = process.argv.includes('--durations-only')
const out = path.join(root, 'public/audio/academy')
const temp = path.join(root, 'node_modules/.tmp/academy-audio')
mkdirSync(temp, { recursive: true })

const ordinal = ['one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve']

function narration(course, episode, index) {
  return [
    `Rev Academy. ${course.title}. Episode ${ordinal[index] ?? index + 1}: ${episode.title}.`,
    episode.summary,
    `In this episode we open the Scriptures together and look at what this means for everyday life.`,
    `Take a quiet moment after listening to pray about what stood out to you. Then, when you are ready, continue to the next episode.`,
  ].join(' ')
}

function speak(text, wav, voice) {
  const escaped = text.replace(/'/g, "''")
  const script = `Add-Type -AssemblyName System.Speech; $s = New-Object System.Speech.Synthesis.SpeechSynthesizer; try { $s.SelectVoice('${voice}') } catch {}; $s.Rate = -1; $s.SetOutputToWaveFile('${wav.replace(/'/g, "''")}'); $s.Speak('${escaped}'); $s.Dispose()`
  execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script], { stdio: 'inherit' })
}

function seconds(file) {
  const value = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nw=1:nk=1', file]).toString().trim()
  return Math.round(Number(value))
}

const durations = {}
for (const [courseIndex, course] of COURSES.entries()) {
  const dir = path.join(out, course.slug)
  mkdirSync(dir, { recursive: true })
  durations[course.slug] = []
  for (const [index, episode] of course.episodes.entries()) {
    const mp3 = path.join(dir, `${index + 1}.mp3`)
    if (!durationsOnly) {
      const wav = path.join(temp, `${course.slug}-${index + 1}.wav`)
      speak(narration(course, episode, index), wav, courseIndex % 2 ? 'Microsoft David Desktop' : 'Microsoft Zira Desktop')
      // Mono speech at 48 kbps keeps each file small.
      execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav, '-ac', '1', '-ar', '24000', '-b:a', '48k', mp3])
      rmSync(wav)
    }
    durations[course.slug].push(existsSync(mp3) ? seconds(mp3) : 0)
    console.log(`${course.slug} ${index + 1}: ${durations[course.slug].at(-1)}s`)
  }
}

writeFileSync(path.join(root, 'src/lib/academy-audio.generated.ts'), `// Generated by scripts/build-academy-audio.mjs. Seconds per episode, by course slug.\nexport const EPISODE_SECONDS: Record<string, number[]> = ${JSON.stringify(durations, null, 2)}\n`)
console.log('done')
